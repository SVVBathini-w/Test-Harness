/** File names inside runs/<run-id>/. */
export const RUN_FILE = {
  run: 'run.json',
  results: 'results.json',
  summary: 'summary.json',
  triage: 'triage.json',
  exploration: 'exploration.md',
  review: 'review.json',
  assessment: 'assessment.json',
  evidenceDir: 'evidence',
  logsDir: 'logs',
  gate: (name) => `gate-${name}.json`
};

/** Generated into reports/. Written by bin/qa-reports.mjs and bin/generate-html-report.mjs only. */
export const REPORT_FILE = {
  html: 'report.html',
  report: 'report.md',
  execution: 'execution.md',
  traceability: 'traceability.md',
  defects: 'defects.md',
  review: 'review.md'
};

export const RUN_ID_PATTERN = /^\d{8}-\d{6}-[0-9a-f]{4}$/;

const readJson = (p) => {
  try { return JSON.parse(readFileSync(p, 'utf8')); } catch { return null; }
};

export const latestRunId = (projectDir) => readJson(join(projectDir, REL.project))?.latest_run ?? null;

export const runDir = (projectDir, runId = latestRunId(projectDir)) =>
  runId ? join(projectDir, REL.runs, runId) : null;

/**
 * Turn a stored relative path into an absolute one. `runs/@latest/x` becomes
 * `runs/<latest_run>/x`; with no run recorded the result is null, which every caller
 * treats as "missing" and never as an error to paper over.
 */
export function resolveRel(projectDir, rel) {
  if (!rel.includes('@latest')) return join(projectDir, rel);
  const id = latestRunId(projectDir);
  return id ? join(projectDir, rel.replace('@latest', id)) : null;
}

/** Absolute paths for a project, with the run-scoped ones bound to `runId` (default: latest). */
export function layoutFor(projectDir, runId = latestRunId(projectDir)) {
  const abs = Object.fromEntries(Object.entries(REL).map(([k, v]) => [k, join(projectDir, v)]));
  const rd = runId ? join(projectDir, REL.runs, runId) : null;
  const run = rd && {
    id: runId,
    dir: rd,
    ...Object.fromEntries(
      Object.entries(RUN_FILE).filter(([, v]) => typeof v === 'string').map(([k, v]) => [k, join(rd, v)])
    ),
    gate: (name) => join(rd, RUN_FILE.gate(name))
  };
  const reports = Object.fromEntries(Object.entries(REPORT_FILE).map(([k, v]) => [k, join(projectDir, REL.reports, v)]));
  return { ...abs, run, reports, designFile: (n) => join(projectDir, REL.designDir, `layer-${n}.md`) };
}

/** Directories qa-init creates. Run folders are created by bin/qa-runs.mjs, not here. */

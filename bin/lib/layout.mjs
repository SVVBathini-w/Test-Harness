/**
 * What lives where inside a project. Every script, hook and generator takes its paths
 * from here, so a rename is one edit and a test can prove no prompt or document
 * still names a path this module does not define.
 *
 *   project.json     identity, mode, target, stage, gates, framework, suite, latest_run
 *   inputs/          what people provided: requirement documents, defect CSVs, answers
 *   spec/            WHAT must be proven. Source of truth, schema-validated.
 *   analysis/        WHAT exists: discovery, coverage, hotspots, change impact
 *   registry/        long-lived records: inventory, defects, evidence, heals, scores
 *   knowledge/       optional durable knowledge with provenance (phase 12)
 *   suite/           the test project (mode new). Mode existing points at the team's own repo.
 *   runs/<run-id>/   one folder per execution. Gitignored. Never overwritten.
 *   reports/         generated by script from the above. No agent writes here.
 *
 * Artefacts that belong to one execution live under runs/<run-id>/. The token
 * `@latest` stands for project.json -> latest_run wherever a relative path is stored
 * (see PHASES in pipeline.mjs) and is resolved by `resolveRel`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';


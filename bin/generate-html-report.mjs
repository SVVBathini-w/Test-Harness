#!/usr/bin/env node
/**
 * Self-contained HTML test report, rendered deterministically from artefacts on disk.
 *
 *   node bin/generate-html-report.mjs <slug> [--run <run-id>] [--title <text>] [--environment <env>] [--out <path>]
 *
 * Reads, for the project resolved by bin/lib/paths.mjs and the latest run (or --run):
 *   runs/<run>/summary.json      REQUIRED, produced by bin/qa-results.mjs
 *   registry/defects.json        optional, validated against its schema
 *   registry/inventory.json      optional, supplies oracle strength
 *   runs/<run>/assessment.json   optional, supplies the verdict an agent recorded
 *
 * Writes reports/report.html unless --out is given. reports/ is generated by script only.
 *
 * There is no fallback data. A missing results summary is an error, not a reason to
 * render sample numbers: a report with invented figures is indistinguishable from a
 * real one. Every value from an artefact is HTML-escaped, since test names and error
 * messages are untrusted data (CLAUDE.md section 16).
 *
 * Exit codes: 0 written, 1 input missing or invalid, 2 usage.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { loadFacts, FactError, esc, openConfirmed, evidenceCoverage } from './lib/facts.mjs';
import { REL, REPORT_FILE } from './lib/layout.mjs';

const die = (code, msg) => { console.error(msg); process.exit(code); };
const argv = process.argv.slice(2);
const flag = (n) => { const i = argv.indexOf(`--${n}`); return i === -1 ? null : argv[i + 1] ?? null; };

const slug = argv[0];
if (!slug || slug.startsWith('--')) {
  die(2, 'Usage: generate-html-report.mjs <slug> [--run <run-id>] [--title <text>] [--environment <env>] [--out <path>]');
}
if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) die(2, `Invalid slug "${slug}".`);

let facts;
try { facts = loadFacts(slug, { runId: flag('run'), only: ['summary', 'defects', 'inventory', 'assessment'] }); } catch (e) { if (e instanceof FactError) die(1, e.message); throw e; }
const { dir, project, summary, assessment } = facts;
if (!facts.runId || !summary) {
  die(1, `No results summary for ${facts.runId ? `run ${facts.runId}` : 'any run'}.\nThe suite has not run, or the summary was not generated. Run: node bin/qa-results.mjs ${slug}\nNot rendering a report without observed results.`);
}
if (!summary.totals || typeof summary.totals.total !== 'number') die(1, `runs/${facts.runId}/summary.json has no totals.total; regenerate it with qa-results.mjs.`);
const defects = facts.defects;
const inventory = facts.inventory;

// ---------------------------------------------------------------- derived figures

const n = (v) => Number(v ?? 0);
const t = summary.totals;
const passed = n(t.passed), failed = n(t.failed), skipped = n(t.skipped), flaky = n(t.flaky);
const pct = (a, b) => (b ? ((a / b) * 100).toFixed(1) : '0.0');

const ec = evidenceCoverage(summary, inventory);
const evidence = ec === null
  ? { text: 'unknown', note: 'No test inventory, so oracle strength was not assessed.' }
  : { text: `${ec.sound} of ${ec.passed}`, note: `${ec.unrated} passing test(s) have no oracle rating; they are not counted as sound.` };
const passingTests = { length: ec?.passed ?? 0 };

const open = openConfirmed(defects);
const verdict = failed > 0 || open.length
  ? { text: 'ATTENTION REQUIRED', cls: 'bad' }
  : flaky > 0 || skipped > 0 ? { text: 'PASSED WITH RESERVATIONS', cls: 'warn' } : { text: 'PASSED', cls: 'ok' };

const layerRows = Object.entries(summary.by_layer ?? {}).sort((a, b) => Number(a[0]) - Number(b[0]))
  .map(([l, c]) => `<tr><td>${esc(l)}</td><td>${n(c.total)}</td><td>${n(c.passed)}</td><td>${n(c.failed)}</td><td>${n(c.skipped)}</td><td>${n(c.flaky)}</td></tr>`).join('');

const failureRows = (summary.failures ?? []).map((f) => `<tr>
  <td>${esc(f.case_id ?? '')}</td><td>${esc(f.title)}</td><td>${esc(f.layer ?? '')}</td><td>${esc(f.status)}</td>
  <td><pre>${esc(String(f.error ?? '').slice(0, 800))}</pre></td></tr>`).join('');

const defectRows = (defects ?? []).map((d) => `<tr>
  <td>${esc(d.id)}</td><td>${esc(d.title)}</td><td>${esc(d.state)}</td><td class="sev-${esc(d.severity)}">${esc(d.severity)}</td><td>${esc(d.component)}</td></tr>`).join('');

const title = flag('title') ?? `${project.display_name ?? slug} — test report`;
const env = flag('environment') ?? project.target?.environment ?? 'unspecified';
const assessed = assessment
  ? `<p class="note"><b>Recorded verdict:</b> ${esc(assessment.verdict)}. ${esc(assessment.recommendation)}</p>`
  : '<p class="note">No release assessment has been recorded for this run.</p>';

const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
:root{--bg:#f6f7f9;--fg:#1c2330;--card:#fff;--line:#dde1e8;--ok:#1b7f3b;--warn:#b25e00;--bad:#b3261e;--mute:#5b6577}
@media (prefers-color-scheme:dark){:root{--bg:#12161d;--fg:#e6e9ef;--card:#1a2029;--line:#2b3340;--ok:#4cc474;--warn:#f0a347;--bad:#ff6b61;--mute:#9aa4b5}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif}
main{max-width:1100px;margin:0 auto;padding:24px 16px}
h1{margin:0 0 4px;font-size:1.6rem}h2{margin:32px 0 10px;font-size:1.15rem}
.meta{color:var(--mute);font-size:.9rem}
.verdict{display:inline-block;margin-top:12px;padding:4px 12px;border-radius:999px;font-weight:600;border:1px solid currentColor}
.ok{color:var(--ok)}.warn{color:var(--warn)}.bad{color:var(--bad)}
.cards{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px;margin-top:20px}
.card{background:var(--card);border:1px solid var(--line);border-radius:8px;padding:12px 14px}
.card b{display:block;font-size:1.5rem}.card span{color:var(--mute);font-size:.85rem}
table{width:100%;border-collapse:collapse;background:var(--card);border:1px solid var(--line);border-radius:8px;overflow:hidden}
th,td{text-align:left;padding:8px 10px;border-bottom:1px solid var(--line);vertical-align:top}th{font-size:.8rem;color:var(--mute);text-transform:uppercase}
pre{margin:0;white-space:pre-wrap;word-break:break-word;font:12px/1.4 ui-monospace,monospace;max-width:420px}
.sev-critical,.sev-high{color:var(--bad);font-weight:600}.sev-medium{color:var(--warn)}
.scroll{overflow-x:auto}.note{color:var(--mute);font-size:.85rem;margin-top:6px}
</style></head><body><main>
<h1>${esc(title)}</h1>
<div class="meta">Project ${esc(slug)} · run ${esc(facts.runId)} · environment ${esc(env)} · results from ${esc(summary.source ?? 'results.json')}</div>
<div class="verdict ${verdict.cls}">${verdict.text}</div>
${assessed}
<div class="cards">
<div class="card"><b>${n(t.total)}</b><span>tests run</span></div>
<div class="card"><b class="ok">${passed}</b><span>passed (${pct(passed, n(t.total))}%)</span></div>
<div class="card"><b class="${failed ? 'bad' : ''}">${failed}</b><span>failed</span></div>
<div class="card"><b class="${flaky ? 'warn' : ''}">${flaky}</b><span>flaky</span></div>
<div class="card"><b class="${skipped ? 'warn' : ''}">${skipped}</b><span>skipped</span></div>
<div class="card"><b>${esc(evidence.text)}</b><span>passing tests with a sound oracle</span></div>
</div>
<p class="note">${esc(evidence.note)} A pass rate alone is not a release verdict.</p>
<h2>By layer</h2>
<div class="scroll"><table><tr><th>Layer</th><th>Total</th><th>Passed</th><th>Failed</th><th>Skipped</th><th>Flaky</th></tr>${layerRows || '<tr><td colspan="6">No layer data in the summary.</td></tr>'}</table></div>
<h2>Failures needing triage (${(summary.failures ?? []).length})</h2>
<div class="scroll"><table><tr><th>Case</th><th>Test</th><th>Layer</th><th>Status</th><th>Error</th></tr>${failureRows || '<tr><td colspan="5">None.</td></tr>'}</table></div>
<p class="note">A failing test is not a defect until it is classified and confirmed.</p>
<h2>Defects</h2>
${defects === null
    ? '<p class="note">No defect register exists for this project, so none are reported. That is absence of a register, not evidence of zero defects.</p>'
    : `<div class="scroll"><table><tr><th>ID</th><th>Title</th><th>State</th><th>Severity</th><th>Component</th></tr>${defectRows || '<tr><td colspan="5">Register is empty.</td></tr>'}</table></div>`}
${(summary.untraced ?? []).length ? `<h2>Untraced tests</h2><p class="note">${(summary.untraced).length} test(s) carry no intent id and will fail the traceability gate.</p>` : ''}
<p class="note">Generated by bin/generate-html-report.mjs from artefacts on disk. No values are estimated.</p>
</main></body></html>
`;

const out = resolve(flag('out') ?? join(dir, REL.reports, REPORT_FILE.html));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`Report written: ${out}`);
console.log(`  ${n(t.total)} tests: ${passed} passed, ${failed} failed, ${flaky} flaky, ${skipped} skipped. Evidence coverage: ${evidence.text}.`);

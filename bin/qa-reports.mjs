#!/usr/bin/env node
/**
 * Generated reports. Nothing under reports/ is written by an agent: each file is
 * rendered here from spec/, registry/ and one run, so a number in a report is always a
 * number that was measured and the report cannot drift from the data.
 *
 *   node bin/qa-reports.mjs execution    <slug> [--run <run-id>]   reports/execution.md
 *   node bin/qa-reports.mjs traceability <slug> [--run <run-id>]   reports/traceability.md + runs/<id>/gate-traceability.json
 *   node bin/qa-reports.mjs review       <slug> [--run <run-id>]   reports/review.md
 *   node bin/qa-reports.mjs report       <slug> [--run <run-id>]   reports/report.md
 *   node bin/qa-reports.mjs all          <slug> [--run <run-id>]   everything above, plus defects.md and report.html
 *
 * `report` renders the agent's recorded judgement (runs/<id>/assessment.json) beside
 * measured facts, and REFUSES a verdict the facts contradict: a pass-grade verdict while
 * a confirmed high or critical defect is open, or while a blocking gate has failed.
 *
 * `traceability` is deterministic: it matches requirement, intent, case and test ids
 * in the artefacts and in the suite's own source, and writes the traceability gate.
 *
 * Exit 0 rendered, 1 a prerequisite is missing or the facts contradict the judgement, 2 usage.
 */
import { writeFileSync, mkdirSync, readdirSync, readFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import validate from './lib/schema.mjs';
import { HARNESS_ROOT, suiteDir } from './lib/paths.mjs';
import { REL, REPORT_FILE, RUN_FILE } from './lib/layout.mjs';
import { loadFacts, FactError, md, openConfirmed, evidenceCoverage } from './lib/facts.mjs';

const die = (code, msg) => { console.error(msg); process.exit(code); };
const [, , cmd, slug, ...rest] = process.argv;
const USAGE = 'Usage: qa-reports.mjs <execution|traceability|review|report|all> <slug> [--run <run-id>]';
if (!cmd || !slug) die(2, USAGE);
const flag = (n) => { const i = rest.indexOf(`--${n}`); return i === -1 ? null : rest[i + 1] ?? null; };

const ONLY = {
  execution: ['run', 'summary', 'triage', 'heals'],
  traceability: ['run', 'summary', 'inventory', 'intents', 'requirements'],
  review: ['run', 'review'],
  report: ['run', 'summary', 'assessment', 'defects', 'inventory', 'intents'],
  all: ['run']
};
if (!ONLY[cmd]) die(2, USAGE);

let F;
try { F = loadFacts(slug, { runId: flag('run'), only: ONLY[cmd] }); } catch (e) { if (e instanceof FactError) die(1, e.message); throw e; }

const reportsDir = join(F.dir, REL.reports);
const emit = (file, text) => {
  mkdirSync(reportsDir, { recursive: true });
  writeFileSync(join(reportsDir, file), text.endsWith('\n') ? text : `${text}\n`);
  console.log(`Wrote reports/${file}`);
};
const needRun = (what) => { if (!F.runId || !F.summary) die(1, `${what} needs a run with a summary. Run: node bin/qa-runs.mjs new ${slug}, execute, then node bin/qa-results.mjs ${slug}`); };
const table = (head, rows) => rows.length
  ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(md).join(' | ')} |`)].join('\n')
  : '_None._';
const stamp = (title) => `# ${title}\n\nProject ${slug} · run ${F.runId}${F.run ? ` · started ${F.run.started} · scope ${F.run.scope} · budget ${F.run.budget}${F.run.change_ref ? ` · change ${F.run.change_ref}` : ''}${F.run.commit ? ` · commit ${F.run.commit}` : ''}` : ''}\n\nGenerated by bin/qa-reports.mjs from artefacts on disk. Do not edit.\n`;

// ------------------------------------------------------------------ execution

function execution() {
  needRun('The execution report');
  const t = F.summary.totals;
  const byTest = new Map((F.triage?.failures ?? []).map((f) => [f.case_id ?? f.test, f]));
  const classify = (f) => byTest.get(f.case_id ?? f.title) ?? byTest.get(f.title);
  const failures = F.summary.failures ?? [];
  const unclassified = failures.filter((f) => !classify(f));
  const heals = (F.heals ?? []).filter((h) => h.run === F.runId);

  const layerRows = Object.entries(F.summary.by_layer ?? {}).sort((a, b) => a[0] - b[0])
    .map(([l, c]) => [l, c.total, c.passed, c.failed, c.skipped, c.flaky]);
  emit(REPORT_FILE.execution, [
    stamp('Execution report'),
    '## Totals', '',
    `${t.total} tests: ${t.passed ?? 0} passed, ${t.failed ?? 0} failed, ${t.flaky ?? 0} flaky, ${t.skipped ?? 0} skipped.`, '',
    '## By layer', '', table(['Layer', 'Total', 'Passed', 'Failed', 'Skipped', 'Flaky'], layerRows), '',
    '## Failures', '',
    table(['Test', 'Layer', 'Status', 'Class', 'Root cause', 'Defect'],
      failures.map((f) => { const c = classify(f); return [f.title, f.layer ?? '', f.status, c?.classification ?? 'UNCLASSIFIED', c?.root_cause ?? '', c?.defect_id ?? '']; })), '',
    unclassified.length
      ? `**${unclassified.length} failure(s) are unclassified. The execution gate cannot pass.**`
      : failures.length ? 'Every failure is classified.' : 'No failures.', '',
    '## Heals in this run', '',
    table(['Id', 'Test', 'Problem', 'Change', 'Validation'], heals.map((h) => [h.id, h.test, h.problem, h.change, h.validation])), '',
    '## Tests with no intent id', '',
    (F.summary.untraced ?? []).length ? (F.summary.untraced).map((x) => `- ${md(x)}`).join('\n') : '_None._'
  ].join('\n'));
  if (unclassified.length) { console.error(`${unclassified.length} unclassified failure(s): ${unclassified.map((f) => f.title).join('; ')}`); process.exitCode = 1; }
}

// --------------------------------------------------------------- traceability

const CODE = /\.(ts|tsx|js|mjs|cjs|py|java|cs|rb|go|kt|feature)$/i;
function idsInSuite() {
  const root = suiteDir(F.proj);
  const found = new Set();
  if (!root || !existsSync(root)) return { root, found };
  const walk = (d, depth = 0) => {
    if (depth > 8) return;
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p, depth + 1);
      else if (CODE.test(e.name) && statSync(p).size < 1_000_000) for (const m of readFileSync(p, 'utf8').matchAll(/\b(?:TC|TI)-[A-Z0-9-]+\b/g)) found.add(m[0]);
    }
  };
  walk(root);
  return { root, found };
}

const NON_TEST_OUTCOMES = new Set(['NO_NEW_TEST_REQUIRED', 'NO_CHANGE_REQUIRED', 'MANUAL_TEST_REQUIRED', 'TESTABILITY_IMPROVEMENT_REQUIRED', 'INSUFFICIENT_EVIDENCE', 'BLOCKED_BY_ENVIRONMENT', 'BLOCKED_BY_PRODUCT_DEFECT']);
const MANUAL = new Set(['MANUAL', 'MANUAL_BY_NECESSITY', 'NOT_AUTOMATABLE', 'AUTOMATION_PLANNED']);

function traceability() {
  needRun('The traceability report');
  if (!F.intents) die(1, 'No spec/intents.json, so nothing can be traced.');
  if (!F.inventory) die(1, 'No registry/inventory.json, so intents cannot be traced to cases.');
  const { found: inSource } = idsInSuite();
  const ranIds = new Set((F.summary.tests ?? []).map((t) => t.case_id).filter(Boolean));
  const blocking = [];
  const add = (id, summary, artefact) => blocking.push({ id, summary, artefact });

  // Direction 1: every requirement is carried by an intent.
  const reqIds = F.requirementsText ? [...new Set(F.requirementsText.match(/\bR-\d{2,}\b/g) ?? [])] : [];
  const refText = (F.intents ?? []).map((i) => JSON.stringify(i.requirement_refs ?? [])).join(' ');
  const uncarried = reqIds.filter((r) => !refText.includes(r));
  uncarried.forEach((r) => add(`TR-D1-${r}`, `Requirement ${r} is referenced by no intent.`, REL.requirements));

  // Direction 2: every intent is carried by a case, or explicitly excluded with an outcome.
  const casesFor = (id) => F.inventory.filter((c) => (c.intent_ids ?? []).includes(id));
  const excluded = [], open = [];
  for (const i of F.intents) {
    if (casesFor(i.id).length || (i.test_refs ?? []).length) continue;
    if (NON_TEST_OUTCOMES.has(i.outcome)) excluded.push(i); else open.push(i);
  }
  open.forEach((i) => add(`TR-D2-${i.id}`, `Intent ${i.id} has no case and outcome ${i.outcome ?? 'unset'} does not exclude it.`, REL.inventory));

  // Direction 3: every automated case exists in code (executed this run, or present in the suite source).
  const inCode = (id) => ranIds.has(id) || inSource.has(id);
  const absent = F.inventory.filter((c) => !MANUAL.has(c.automation_status) && !inCode(c.case_id));
  absent.forEach((c) => add(`TR-D3-${c.case_id}`, `Case ${c.case_id} is marked ${c.automation_status} but its id appears in no executed test and no suite source.`, REL.suite));

  // Direction 4: every test traces back to a known case and intent.
  const known = new Set(F.inventory.map((c) => c.case_id));
  const orphans = (F.summary.tests ?? []).filter((t) => !t.case_id || !known.has(t.case_id));
  orphans.forEach((t) => add(`TR-D4-${t.case_id ?? t.title}`, `Test "${t.title ?? t.case_id}" traces to no case in the inventory.`, `runs/${F.runId}/${RUN_FILE.summary}`));

  const required = F.intents.length - excluded.length;
  const closed = required - open.length;
  const coverage = required > 0 ? Math.round((closed / required) * 1000) / 10 : 100;
  const passed = blocking.length === 0;

  const gate = {
    gate: 'traceability', passed, blocking, coverage,
    evidence: `${F.intents.length} intents, ${F.inventory.length} cases, ${(F.summary.tests ?? []).length} executed tests, ${inSource.size} ids found in suite source; requirements parsed: ${reqIds.length}.`,
    confidence: reqIds.length ? 'high' : 'medium',
    metrics: { intents: F.intents.length, excluded: excluded.length, cases: F.inventory.length, orphan_tests: orphans.length, requirements: reqIds.length },
    produced_at: new Date().toISOString(), produced_by: 'bin/qa-reports.mjs traceability'
  };
  const errors = validate(gate, JSON.parse(readFileSync(join(HARNESS_ROOT, 'schemas', 'gate-result.schema.json'), 'utf8')));
  if (errors.length) die(1, `Generated an invalid gate record:\n${errors.map((e) => `  - ${e}`).join('\n')}`);
  writeFileSync(join(F.runDir, RUN_FILE.gate('traceability')), JSON.stringify(gate, null, 2) + '\n');

  emit(REPORT_FILE.traceability, [
    stamp('Traceability'),
    `Four-direction closure: **${coverage}%** of ${required} intents that require a test (${excluded.length} explicitly excluded). Gate: **${passed ? 'PASS' : 'FAIL'}**.`, '',
    '## Intent to case to test', '',
    table(['Intent', 'Outcome', 'Cases', 'Executed'],
      F.intents.map((i) => { const cs = casesFor(i.id); return [i.id, i.outcome ?? '', cs.map((c) => c.case_id).join(', ') || (excluded.includes(i) ? '(excluded)' : '—'), cs.filter((c) => ranIds.has(c.case_id)).length]; })), '',
    '## Findings', '', table(['Id', 'Finding', 'Artefact'], blocking.map((b) => [b.id, b.summary, b.artefact])), '',
    '## Direction 4 orphans', '', orphans.length ? orphans.map((t) => `- ${md(t.title ?? t.case_id)}`).join('\n') : '_None._'
  ].join('\n'));
  console.log(`Wrote runs/${F.runId}/gate-traceability.json (${passed ? 'pass' : 'fail'}, coverage ${coverage}%)`);
  if (!passed) process.exitCode = 1;
}

// --------------------------------------------------------------------- review

function review() {
  if (!F.review) die(1, `No runs/${F.runId}/review.json. The independent review has not been recorded.`);
  const ec = F.review.evidence_coverage;
  emit(REPORT_FILE.review, [
    stamp('Independent review'),
    `Evidence coverage: **${ec.sound} of ${ec.passed}** passing tests carry an oracle that survived the audit.${ec.note ? ` ${md(ec.note)}` : ''}`, '',
    '## Findings', '',
    table(['Id', 'Severity', 'Kind', 'Artefact', 'Summary', 'Siblings checked', 'Remediation'],
      F.review.findings.map((f) => [f.id, f.severity, f.kind, f.artefact, f.summary, (f.siblings_checked ?? []).join(', '), f.remediation ?? '']))
  ].join('\n'));
}

// --------------------------------------------------------------------- report

const PASS_GRADE = new Set(['PASS_RECOMMENDATION', 'QUALITY_CONFIDENCE_HIGH']);

function report() {
  needRun('The QA report');
  const a = F.assessment;
  if (!a) die(1, `No runs/${F.runId}/assessment.json. The release assessment is the agent's judgement and has not been recorded; nothing is rendered in its place.`);

  const open = openConfirmed(F.defects);
  const serious = open.filter((d) => ['critical', 'high'].includes(d.severity));
  const failedGates = Object.entries(F.project.gates ?? {}).filter(([k, g]) => g.status === 'fail' && k !== 'session_score').map(([k]) => k);
  const contradictions = [];
  if (PASS_GRADE.has(a.verdict) && serious.length) contradictions.push(`verdict ${a.verdict} while ${serious.length} confirmed ${serious.map((d) => d.severity).join('/')} defect(s) are open (${serious.map((d) => d.id).join(', ')})`);
  if (PASS_GRADE.has(a.verdict) && failedGates.length) contradictions.push(`verdict ${a.verdict} while blocking gate(s) failed: ${failedGates.join(', ')}`);
  if (a.verdict === 'PASS_WITH_RISK' && failedGates.length) contradictions.push(`verdict PASS_WITH_RISK while blocking gate(s) failed: ${failedGates.join(', ')}`);
  if (a.run !== F.runId) contradictions.push(`assessment is for run ${a.run}, not ${F.runId}`);
  const unknownBlockers = (a.release_blockers ?? []).filter((id) => !(F.defects ?? []).some((d) => d.id === id));
  if (unknownBlockers.length) contradictions.push(`release_blockers name defects not in the register: ${unknownBlockers.join(', ')}`);
  if (contradictions.length) die(1, `The recorded assessment contradicts the facts, so no report is rendered:\n${contradictions.map((c) => `  - ${c}`).join('\n')}\nCorrect runs/${F.runId}/assessment.json, or fix what it contradicts.`);

  const t = F.summary.totals;
  const ec = evidenceCoverage(F.summary, F.inventory);
  const sevCount = (s) => open.filter((d) => d.severity === s).length;
  const gateRows = ['execution', 'code_quality', 'traceability', 'reporting', 'session_score'].map((g) => [g, F.project.gates?.[g]?.status ?? 'pending', F.project.gates?.[g]?.run ?? '']);
  emit(REPORT_FILE.report, [
    stamp('QA report'),
    `**${md(a.recommendation)}**`, '',
    `Verdict: \`${a.verdict}\` · confidence ${a.confidence}.`, '',
    '## What was tested', '',
    `${t.total} tests in run ${F.runId}: ${t.passed ?? 0} passed, ${t.failed ?? 0} failed, ${t.flaky ?? 0} flaky, ${t.skipped ?? 0} skipped. Layers enabled: ${F.project.layers.join(', ')}. Intents: ${F.intents?.length ?? 'not recorded'}; cases: ${F.inventory?.length ?? 'not recorded'}.`, '',
    '## What was not tested', '',
    [...(a.not_tested ?? []), ...(a.skipped ?? []).map((s) => `SKIPPED: ${s}`)].map((x) => `- ${md(x)}`).join('\n') || '_Nothing recorded._', '',
    '## Results by layer', '',
    table(['Layer', 'Total', 'Passed', 'Failed', 'Skipped', 'Flaky'], Object.entries(F.summary.by_layer ?? {}).sort((x, y) => x[0] - y[0]).map(([l, c]) => [l, c.total, c.passed, c.failed, c.skipped, c.flaky])), '',
    '## Defects', '',
    `Open confirmed: ${open.length} (critical ${sevCount('critical')}, high ${sevCount('high')}, medium ${sevCount('medium')}, low ${sevCount('low')}). Register total: ${F.defects?.length ?? 0}.`, '',
    table(['Id', 'Severity', 'State', 'Title'], open.map((d) => [d.id, d.severity, d.state, d.title])), '',
    '## Evidence quality', '',
    ec ? `Evidence coverage: **${ec.sound} of ${ec.passed}** passing tests carry a STRONG or ADEQUATE oracle (${ec.unrated} unrated).` : 'Evidence coverage: **not assessed** (no test inventory).', '',
    '## Quality gates', '', table(['Gate', 'Status', 'Run'], gateRows), '',
    '## Release assessment', '',
    table(['Factor', 'Finding'], (a.rationale ?? []).map((r) => [r.factor, r.finding])), '',
    '## Residual risk', '', (a.residual_risk ?? []).map((x) => `- ${md(x)}`).join('\n') || '_None stated._', '',
    '## Known limitations', '', (a.known_limitations ?? []).map((x) => `- ${md(x)}`).join('\n') || '_None stated._', '',
    '## Next actions', '', table(['Priority', 'Action', 'Owner', 'Effort'], (a.next_actions ?? []).map((n) => [n.priority, n.action, n.owner ?? '', n.effort ?? '']))
  ].join('\n'));
}

// ------------------------------------------------------------------------ all

function all() {
  const steps = [['execution', execution], ['traceability', traceability], ['review', review], ['report', report]];
  const skipped = [], failed = [];
  for (const [name, fn] of steps) {
    const before = process.exitCode;
    try {
      // `die` exits the process; run each step in a child so one missing prerequisite is reported, not fatal.
      const r = spawnSync(process.execPath, [process.argv[1], name, slug, ...(flag('run') ? ['--run', flag('run')] : [])], { encoding: 'utf8' });
      process.stdout.write(r.stdout);
      if (r.status !== 0) { (r.status === 1 ? skipped : failed).push(`${name}: ${r.stderr.trim().split('\n')[0]}`); }
    } catch (e) { failed.push(`${name}: ${e.message}`); }
    process.exitCode = before;
  }
  for (const [label, script, args] of [['defects', 'qa-defects.mjs', ['mirror', slug]], ['html', 'generate-html-report.mjs', [slug, ...(flag('run') ? ['--run', flag('run')] : [])]]]) {
    const r = spawnSync(process.execPath, [join(HARNESS_ROOT, 'bin', script), ...args], { encoding: 'utf8' });
    process.stdout.write(r.stdout);
    if (r.status !== 0) skipped.push(`${label}: ${(r.stderr || r.stdout).trim().split('\n')[0]}`);
  }
  if (skipped.length) console.error(`\nNOT RENDERED (prerequisite missing or facts disagree):\n${skipped.map((s) => `  - ${s}`).join('\n')}`);
  if (failed.length) console.error(`\nFAILED:\n${failed.map((s) => `  - ${s}`).join('\n')}`);
  process.exitCode = skipped.length || failed.length ? 1 : 0;
}

const run = { execution, traceability, review, report, all }[cmd];
if (!run) die(2, USAGE);
run();
